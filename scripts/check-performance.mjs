import assert from 'node:assert/strict';
import { FramePacing, adaptiveScale } from '../src/core/AdaptiveQuality.js';
import { Game } from '../src/core/Game.js';
const pacing=new FramePacing();let sample;
for(let i=0;i<60;i++)sample=pacing.record(1/60)||sample;
assert.ok(Math.abs(sample.fps-60)<.01);assert.ok(Math.abs(sample.p95-1000/60)<.01);
let state={},scale=.6;
for(let i=0;i<30;i++)scale=adaptiveScale(state,scale,sample);
assert.equal(scale,1,'A 60 Hz capped display recovers to the chosen resolution');
assert.equal(adaptiveScale(state,1,sample),1,'Never exceeds user scale');
scale=adaptiveScale(state,1,{fps:40,p95:30,slowRatio:1});assert.equal(scale,.9);
for(let i=0;i<7;i++)scale=adaptiveScale(state,scale,sample);assert.equal(scale,.9,'Recovery waits after a failed probe');
scale=adaptiveScale(state,scale,sample);assert.equal(scale,.94);
assert.equal(adaptiveScale({},.6,{fps:20,p95:50,slowRatio:1}),.6);
state={};scale=.7;for(let i=0;i<20;i++)scale=adaptiveScale(state,scale,{fps:60,p95:40,slowRatio:.15});assert.equal(scale,.7,'Uneven frames do not trigger recovery');
pacing.record(.02);pacing.record(.02,false);assert.equal(pacing.elapsed,0);
assert.equal(pacing.record(1),null);assert.equal(pacing.elapsed,0,'Background stalls are excluded');
assert.equal(pacing.record(NaN),null);
let resizes=0;const game={adaptiveState:{healthy:2},dynamicScale:.8,applyPixelRatio:()=>true,resize:()=>resizes++};
Game.prototype.adapt.call(game,sample);assert.equal(game.dynamicScale,.84);assert.equal(resizes,1);
console.log('PASS: capped 60 Hz recovery, cooldown, floor/ceiling, jitter rejection, hidden/paused/stalled sampling exclusion and renderer integration.');
